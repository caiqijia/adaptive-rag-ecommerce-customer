# Query Rewrite Agent（重试轮的查询改写）
# ============================================================
# v1.0 2026-10-26 | 消费者：agent_service.rewrite_query()
# 设计要点：
#   1. "结合对话历史"是指代消解的关键："那它呢"必须靠 history 才知道"它"是什么
#   2. "保留原始意图，不扩大范围"防止改写跑题——跑题的改写比不改写更糟
#   3. 一次生成 {n} 条（config.AGENT_QUERY_REWRITE_NUM=3），逐轮取用：
#      既保证多样性，又避免每轮都调一次 LLM 的时延
REWRITE_PROMPT = """你是查询改写器。用户问题可能存在口语化、指代不明、缺少关键词的问题，
请结合对话历史，改写成 {n} 条更适合检索的独立问句（保留原始意图，不扩大范围）。

对话历史：
{history}

原始问题：{question}

只输出JSON：{{"queries": ["改写1", "改写2", ...]}}"""

# ============================================================
# Decompose Agent（D 类复合问题拆解）
# ============================================================
# v1.0 2026-10-26 | 消费者：agent_service.decompose_query()
# 设计要点：
#   1. "不要拆解可以一步回答的简单问题"——防过度拆解：Router 误判 D 类时兜底
#   2. "按依赖顺序排列"——子问题有先后依赖时（先问能不能退，再问运费谁出），
#      顺序影响综合生成时的逻辑连贯性
#   3. {max_sub} 由调用侧传入（agent_service.MAX_SUB_QUESTIONS=4）：限一层、限条数，
#      防递归拆解放大调用次数和时延
DECOMPOSE_PROMPT = """你是问题分解器。请把用户的复合问题拆成可独立检索的子问题，
子问题之间按依赖顺序排列，最多 {max_sub} 个，不要拆解可以一步回答的简单问题。

对话历史：
{history}

原始问题：{question}

只输出JSON：{{"sub_questions": ["子问题1", "子问题2"]}}"""

# ============================================================
# 生成 Agent（带引用回答，C 类单跳）
# ============================================================
# v1.1 2026-10-28 | 消费者：agent_service.generate_answer(sub_mode=False)
# 设计要点：
#   1. 规则1"禁止编造"是 RAG 的底线：知识库没有就说没有，幻觉比拒答更伤信任
#   2. 规则2 引用编号 [1][2] 与精排结果严格对齐——Critic 才有得可审，用户才可溯源
#   3. 规则3 允许说"资料未提及"：给模型一个"安全的出口"，它就不容易编造
# 【v1.1 补了什么】规则2 加了编号范围约束：实测模型会写出 [4]（只有 3 条证据），
#   这类编号前端无处可跳、引用溯源直接断链。同时 _build_context 在上下文末尾
#   声明了合法范围、extract_used_citations 做了越界过滤——三重保险，缺一不可。
ANSWER_PROMPT = """你是电商客服问答助手。请严格依据下方检索资料回答用户问题。

规则：
1. 只能使用资料中的事实，禁止编造资料里没有的信息
2. 每个事实陈述后面标注引用编号，如"支持七天无理由退货[1]"。
   编号只能取资料中实际出现的编号，严禁写出资料里不存在的编号（例如只有 3 条资料却标注 [4]）
3. 资料无法回答的部分，明确说"资料中未提及"，不要猜测
4. 语气亲切、简洁，用中文

检索资料：
{context}

对话历史：
{history}

用户问题：{question}"""

# ============================================================
# 生成 Agent（带引用回答，D 类综合版）
# ============================================================
# v1.1 2026-10-28 | 消费者：agent_service.generate_answer(sub_mode=True)
# 与 ANSWER_PROMPT 的差异（为什么用两套而不是一套）：
#   - D 类的证据来自多个子问题的检索，天然更全，"资料未提及"的出现概率低
#   - D 类要的是"完整连贯的综合回答"，逐句提"资料未提及"会打断连贯性
#   - 但引用编号的要求完全一致——可信度标准不降级（v1.1 同步补上编号范围约束）
SYNTHESIS_PROMPT = """你是电商客服问答助手。用户问题已被拆成多个子问题，
请综合下方全部检索资料，给出完整、连贯的回答。

规则：
1. 只能使用资料中的事实，禁止编造
2. 每个事实陈述后面标注引用编号，如"退货时效是7天[1]"。
   编号只能取资料中实际出现的编号，严禁写出资料里不存在的编号
3. 若某子问题资料不足，只跳过不编造，不要提"资料未提及"
4. 语气亲切、简洁，用中文

检索资料：
{context}

用户问题：{question}"""

# ============================================================
# Critic Agent（溯源校验守门）
# ============================================================
# v1.1 2026-10-28 | 消费者：agent_service.verify_answer()
# 设计要点：
#   1. 判定标准给的是"可操作的判据"（有没有资料外的事实/数字/承诺），
#      而不是抽象的"是否准确"——审核 prompt 最忌空泛
#   2. "拒答或说资料未提及 → 通过"：防止审核器把正确的拒答误判为失败
#   3. temperature=0.1 在调用侧设置：审核是确定性任务，高温会放大随机性
# 【v1.1 补了什么、为什么】
#   v1.0 只写了"事实是否被支撑"，没写"要不要管引用编号"。实测模型会自作主张
#   去核对 [1][2] 标得对不对，一旦标错就判不通过——但这是**标注瑕疵，不是幻觉**。
#   后果是正确回答被拒：实测"优惠券过期了还能补发吗"因"规则出自[1]而非[2]"被拒，
#   内容完全正确、用户看到的是"没能通过内部校验"。
#   Critic 的职责是防幻觉，不是校对引用格式。已在 v1.1 里划清边界：
#   只审事实，不审编号；同一事实能在任意一条资料中找到即算通过。
VERIFY_PROMPT = """你是答案审核员。请判断【回答】中的每个事实陈述是否被【检索资料】支撑。

判定标准：
- 回答中出现资料中完全没有的事实/数字/承诺 → 不通过
- 回答只是资料内容的复述、归纳、合理改写 → 通过
- 回答拒答或说资料未提及 → 通过

【重要边界：只审事实，不审引用编号】
请把回答里的 [1][2][3] 全部当作普通字符忽略掉，完全不要检查：
- 编号标得对不对
- 某句话到底出自哪一条资料
你要判断的只有一件事：这个事实，在【全部资料合起来】的范围里能不能找到。
- 能找到（哪怕分散在多条里、哪怕没标编号）→ passed=true
- 所有资料里都找不到，或与资料矛盾 → passed=false
reason 只写"事实有无支撑"，不要提到引用编号、不要评价标注是否准确。

检索资料：
{context}

待审核回答：
{answer}

只输出JSON：{{"passed": true|false, "reason": "一句话说明"}}"""

